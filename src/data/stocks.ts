function genHistory(start: number, days: number, drift: number, vol: number, seed = 1): { date: string; close: number }[] {
  const out: { date: string; close: number }[] = [];
  let p = start;
  let s = seed;
  const rand = () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
  const today = new Date("2026-05-07");
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const shock = (rand() - 0.5) * vol;
    p = Math.max(1, p * (1 + drift / days + shock));
    out.push({ date: d.toISOString().slice(0, 10), close: Number(p.toFixed(2)) });
  }
  return out;
}

